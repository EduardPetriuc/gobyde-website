const header = document.querySelector("[data-header]");
const menuButton = document.querySelector("[data-menu-toggle]");
const mobileMenu = document.querySelector("[data-mobile-menu]");
const languageButton = document.querySelector("[data-language]");
let currentLanguage = localStorage.getItem("gobyde-language") || "ro";

function setLanguage(language) {
  currentLanguage = language;
  const dictionary = translations[language];
  document.documentElement.lang = language;
  const page = document.body.dataset.page;
  document.title = page === "aura-farm"
    ? (language === "ro" ? "Aura Farm — Joc GoByde" : "Aura Farm — A GoByde game")
    : (language === "ro" ? "GoByde — Jocuri și aplicații mobile" : "GoByde — Mobile games and apps");

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const value = dictionary[element.dataset.i18n];
    if (value) element.innerHTML = value;
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((element) => {
    const value = dictionary[element.dataset.i18nAria];
    if (value) element.setAttribute("aria-label", value);
  });
  document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
    const value = dictionary[element.dataset.i18nAlt];
    if (value) element.setAttribute("alt", value);
  });
  document.querySelectorAll("[data-i18n-content]").forEach((element) => {
    const value = dictionary[element.dataset.i18nContent];
    if (value) element.setAttribute("content", value);
  });

  languageButton.innerHTML = language === "ro"
    ? '<span class="language-active">RO</span><span class="language-divider">/</span><span>EN</span>'
    : '<span>RO</span><span class="language-divider">/</span><span class="language-active">EN</span>';
  languageButton.setAttribute("aria-label", language === "ro" ? "Switch to English" : "Schimbă în română");
  localStorage.setItem("gobyde-language", language);
}

function closeMenu() {
  mobileMenu.classList.remove("open");
  menuButton.setAttribute("aria-expanded", "false");
  document.body.classList.remove("menu-open");
}

menuButton.addEventListener("click", () => {
  const isOpen = menuButton.getAttribute("aria-expanded") === "true";
  menuButton.setAttribute("aria-expanded", String(!isOpen));
  mobileMenu.classList.toggle("open", !isOpen);
  document.body.classList.toggle("menu-open", !isOpen);
});

mobileMenu.querySelectorAll("a").forEach((link) => link.addEventListener("click", closeMenu));
languageButton.addEventListener("click", () => setLanguage(currentLanguage === "ro" ? "en" : "ro"));
window.addEventListener("scroll", () => header.classList.toggle("scrolled", window.scrollY > 24), { passive: true });
window.addEventListener("resize", () => { if (window.innerWidth > 820) closeMenu(); });

const observer = new IntersectionObserver(
  (entries) => entries.forEach((entry) => {
    if (entry.isIntersecting) {
      entry.target.classList.add("visible");
      observer.unobserve(entry.target);
    }
  }),
  { threshold: 0.12 },
);

document.querySelectorAll(".reveal").forEach((element) => {
  element.style.setProperty("--delay", `${element.dataset.delay || 0}ms`);
  observer.observe(element);
});

document.querySelector("[data-year]").textContent = new Date().getFullYear();
setLanguage(currentLanguage);
